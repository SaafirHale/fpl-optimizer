"""Render reports/BACKTEST.md from the JSON results (no number in it is typed by hand).

    py scripts/make_report.py
"""

import json
from pathlib import Path

R = Path(__file__).resolve().parent.parent / "reports"


def load(name):
    p = R / name
    return json.loads(p.read_text()) if p.exists() else None


def f(x, d=3):
    return f"{x:.{d}f}"


def accuracy_table(m, models=("model", "form", "ppg")):
    names = {"model": "This model", "form": "Form (last 4 GWs)", "ppg": "Points per match so far",
             "fpl_lag": "FPL xP, previous GW snapshot"}
    rows = ["| Projection | MAE | RMSE | Pearson r | Rank corr. per GW | Top-50 overlap | Top pick's actual pts |",
            "|---|---:|---:|---:|---:|---:|---:|"]
    for k in models:
        if k not in m:
            continue
        x = m[k]
        rows.append(f"| {names[k]} | {f(x['mae'])} | {f(x['rmse'])} | {f(x['pearson'])} | {f(x['spearman_per_gw'])} | "
                    f"{f(x['top50_overlap'])} | {f(x['captain_pts'], 2)} |")
    return "\n".join(rows)


def main():
    test, val = load("backtest-2025-26.json"), load("backtest-2024-25.json")
    tune, policy = load("tuning-2024-25.json"), load("policy-2024-25.json")
    sims = {s: load(f"simulation-2025-26-{s}.json") for s in ("model", "form")}
    out = ["# Backtest report", "",
           "Generated by `scripts/make_report.py` from the JSON files in this folder.", "",
           "## Method", "",
           "- **Walk-forward, no lookahead.** To project gameweek *t*, the model sees that season's rows from "
           "gameweeks before *t* plus the previous season. The fixture list and prices at *t* are known before "
           "the deadline. `tests/test_model.py::test_no_lookahead` rewrites every row from *t* onward and checks "
           "that the projection for *t* does not change.",
           "- **Validation and test are separate seasons.** Model hyperparameters (`scripts/tune.py`) and the "
           "transfer policy (`scripts/tune_policy.py`) were chosen on **2024/25** only. **2025/26** is the "
           "hold-out season, evaluated with those settings.",
           "- **Ground truth** is the points each player actually scored, from the public per-gameweek dataset "
           "(vaastav/Fantasy-Premier-League). The scoring tables reproduce 100% of those totals from their "
           "components in 2024/25 and 2025/26 (`test_scoring_tables_reproduce_every_actual_score`).",
           "- **Rows:** every player registered in a gameweek whose club played (most score 0). "
           "\"Top pick's actual pts\" is the mean real score of each projection's single highest-projected "
           "player per gameweek, before the captain's double.", ""]
    if test:
        out += [f"## Hold-out season: 2025/26 ({test['rows']:,} player-gameweeks, {test['gameweeks']} gameweeks)", "",
                accuracy_table(test), ""]
        mp = test["model"]["mae_by_pos"]
        out += ["MAE by position (model): " + ", ".join(f"{k} {f(v)}" for k, v in mp.items()) + ".", ""]
        cal = test["calibration"]
        out += ["Calibration, 2025/26 (players grouped by projected points):", "",
                "| Projected | Rows | Mean projected | Mean actual |", "|---|---:|---:|---:|"]
        out += [f"| {c['bucket']} | {c['n']:,} | {f(c['projected'], 2)} | {f(c['actual'], 2)} |" for c in cal]
        out += [""]
        h2h = test.get("vs_fpl_lag")
        if h2h:
            out += [f"Against FPL's own expected points (the previous gameweek's snapshot, the latest one recorded "
                    f"before the deadline), on the {h2h['rows']:,} rows where the dataset has it:", "",
                    accuracy_table(h2h, ("model", "fpl_lag", "form")), ""]
    live = sorted(R.glob("backtest-2026-27-gw*.json"))
    if live:
        lv = json.loads(live[-1].read_text())
        out += [f"## Current season so far: 2026/27 GW{lv['season'].split('gw')[1]} "
                f"({lv['rows']:,} player-gameweeks)", "",
                "Same walk-forward rule, built from the live FPL API (`fplopt backtest live`). Rows are priced as of "
                "each gameweek from Valuo's nightly snapshot (the latest earlier price where the local copy ends), "
                "because today's prices already reflect this season's results. Ten gameweeks is a small sample, "
                "especially for the top-pick column.", "",
                accuracy_table(lv), ""]
    if val:
        out += [f"## Validation season: 2024/25 ({val['rows']:,} player-gameweeks)", "", accuracy_table(val), ""]
        h2h = val.get("vs_fpl_lag")
        if h2h:
            out += ["Against FPL's previous-gameweek xP snapshot, 2024/25:", "",
                    accuracy_table(h2h, ("model", "fpl_lag", "form")), ""]
    lk = (val or {}).get("leakage_check")
    if lk and "fpl_xp" in lk:
        out += ["## Why FPL's same-week xP is not a baseline", "",
                "The dataset's xP column for gameweek *t* looks like a forecast but was recorded after *t*. "
                "An honest forecast for *t* loses a little accuracy on *t+1*; this column correlates with *t* "
                "far better than with *t+1*, and as well with *t-1* as with *t* (2024/25, Pearson r with points):", "",
                "| Column | Last week | This week | Next week |", "|---|---:|---:|---:|"]
        label = {"xp": "This model", "fpl_xp": "FPL xP, same week", "form": "Form", "ppg": "Points per match"}
        out += [f"| {label[k]} | {f(v['prev'])} | {f(v['this'])} | {f(v['next'])} |" for k, v in lk.items()]
        out += ["", "So the comparison above uses the previous gameweek's snapshot instead.", ""]
    if any(sims.values()):
        out += ["## Season replay: 2025/26 with the optimizer", "",
                "The solver runs every gameweek with a 3-week horizon, carrying the squad, bank, selling prices "
                "and free transfers forward. GW1 is a free draft on GBP 100m. Each week is scored on real points "
                "with automatic substitutions and the vice-captain rule. No chips are played. \"Form\" is the same "
                "solver fed the naive form projection.", "",
                "| Projections | Season points | Before hits | Hits taken | Transfers | Best week | Worst week |",
                "|---|---:|---:|---:|---:|---:|---:|"]
        for k, s in sims.items():
            if s:
                pts = [w["points"] for w in s["weeks"]]
                gross = s["total"] + 4 * sum(w["hits"] for w in s["weeks"])
                out.append(f"| {'This model' if k == 'model' else 'Form'} | {s['total']:,} | {gross:,} | "
                           f"{sum(w['hits'] for w in s['weeks'])} | {sum(w['transfers'] for w in s['weeks'])} | "
                           f"{max(pts)} | {min(pts)} |")
        sens = {k: load(f"sensitivity-margin0-2025-26-{k}.json") for k in ("model", "form")}
        if all(sens.values()):
            out += ["", f"Sensitivity: with no extra hit cost (the policy before tuning), the same replay scored "
                    f"{sens['model']['total']:,} with the model ({sum(w['hits'] for w in sens['model']['weeks'])} hits) "
                    f"and {sens['form']['total']:,} with form ({sum(w['hits'] for w in sens['form']['weeks'])} hits)."]
        out += ["", "Noisy projections make the solver chase every swing, so much of the gap is hits; the "
                "\"before hits\" column shows the gap without them. This compares the projections inside the same decision engine. It is not a comparison with "
                "real managers: the public data has no 2025/26 average manager score.", ""]
    if policy:
        out += ["## Transfer policy (chosen on 2024/25)", "",
                "| Extra cost per hit | Value of a banked transfer | 2024/25 replay points | Hits | Transfers |",
                "|---:|---:|---:|---:|---:|"]
        out += [f"| {r['hit_margin']:g} | {r['ft_value']:g} | {r['total']:,} | {r['hits']} | {r['transfers']} |"
                for r in policy["runs"]]
        b = policy["best"]
        out += ["", f"Chosen: extra hit cost {b['hit_margin']:g}, banked-transfer value {b['ft_value']:g}. The totals do "
                "not move in one direction as hit aversion rises, so the choice is partly noise. It is the 2024/25 "
                "maximum, taken mechanically by the script. The zero-margin 2025/26 run in the sensitivity line was "
                "made while tuning was still running and played no part in the choice.", ""]
    if tune:
        b = tune["best_score"]
        start = tune["log"][0]
        out += ["## Hyperparameters (chosen on 2024/25)", "",
                f"Coordinate search over {len(tune['log'])} settings moved validation RMSE from "
                f"{f(start['rmse'])} to {f(b['rmse'])} ({f((val or {}).get('model', {}).get('rmse', float('nan')))} with the "
                "final settings below). Nearly all of the gain came from the minutes model "
                "reacting faster (recency decay 0.6, prior worth one match). Shrinkage of 450 vs 900 prior "
                "minutes differed by less than 0.001 RMSE, so Valuo's 900 is kept.", ""]
    out += ["## Limitations", "",
            "- Historical injury and suspension flags are not archived, so the backtest model has no team news. "
            "Live runs use FPL's `chance_of_playing_next_round`; the backtest understates that.",
            "- Defensive contributions began in 2025/26, so GW1 of the hold-out season has no prior for them; "
            "the pooled rate is learned from GW2 on.",
            "- Prices are held flat over the planning horizon, and the replay plays no chips.",
            "- Most player-gameweeks score 0 or 1, which keeps MAE low for every method; RMSE, correlation "
            "and the replay separate them better.", ""]
    (R / "BACKTEST.md").write_text("\n".join(out), encoding="utf-8")
    print("wrote reports/BACKTEST.md")


if __name__ == "__main__":
    main()
